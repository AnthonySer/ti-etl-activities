/* ============================================================================
   04_validacion_por_empresa.sql
   Una consulta separada por empresa para comparar esquemas y resultados.

   Grupo POBLADO (9): ANDINA, CALCA, FILASUR, INKA, MUNDIAL, NK, POLYSOL,
                     SERVIAM, TROPICAL.
   Grupo VACÍO/MÍNIMO (9): CONDOR, COYA, ESTRATEGO, PROEXPLOR, RELTEX,
                           TANKARPATA, TARAY, TMI, YACLOT.

   Todas las consultas son de SOLO LECTURA. Devuelven los ocho campos lógicos y
   usan NULL donde el esquema no ofrece el dato. No se inventan columnas.
   ============================================================================ */

USE [EXACTUS];
GO

/* ============================ GRUPO POBLADO ============================ */

/* 04.01 — ANDINA (sin U_CORREO_CORP) */
SELECT
    E.EMPLEADO AS EMPLEADO, E.NOMBRE AS NOMBRE, 'ANDINA' AS EMPRESA,
    'EMPLEADO' AS FUENTE,
    COALESCE(D.DESCRIPCION, E.DEPARTAMENTO) AS DEPARTAMENTO,
    COALESCE(P.DESCRIPCION, E.PUESTO) AS PUESTO,
    E.ACTIVO AS ACTIVO, NULLIF(LTRIM(RTRIM(E.E_MAIL)), '') AS CORREO
FROM [EXACTUS].[ANDINA].[EMPLEADO] E
LEFT JOIN [EXACTUS].[ANDINA].[DEPARTAMENTO] D ON D.DEPARTAMENTO = E.DEPARTAMENTO
LEFT JOIN [EXACTUS].[ANDINA].[PUESTO] P ON P.PUESTO = E.PUESTO
ORDER BY E.EMPLEADO;
GO

