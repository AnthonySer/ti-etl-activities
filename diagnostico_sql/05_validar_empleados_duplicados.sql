/* ============================================================================
   05_validar_empleados_duplicados.sql
   Objetivo: revisar coincidencias de empleados entre empresas y fuentes SIN
   fusionar ni eliminar registros.

   Regla del proyecto:
     - El código de empleado NO es único entre empresas.
     - El nombre NO basta para concluir que dos registros son la misma persona.
     - Cada registro (empresa, fuente, código) se conserva por separado.
     - Activo/inactivo en empresas distintas se muestra completo.

   Se consultan las 9 empresas pobladas: ANDINA, CALCA, FILASUR, INKA, MUNDIAL,
   NK, POLYSOL, SERVIAM y TROPICAL. Las 9 empresas vacías no aportan filas.

   SOLO LECTURA. No elimina ni actualiza datos.
   ============================================================================ */

USE [EXACTUS];
GO

/* 05.1 — Código repetido dentro de la misma empresa (debe ser 0 en los datos
   verificados; si aparece, indica un problema de la fuente, no del proceso). */
WITH EMPLEADOS AS (
    SELECT 'ANDINA' AS EMPRESA, EMPLEADO, NOMBRE FROM [EXACTUS].[ANDINA].[EMPLEADO]
    UNION ALL SELECT 'CALCA', EMPLEADO, NOMBRE FROM [EXACTUS].[CALCA].[EMPLEADO]
    UNION ALL SELECT 'FILASUR', EMPLEADO, NOMBRE FROM [EXACTUS].[FILASUR].[EMPLEADO]
    UNION ALL SELECT 'INKA', EMPLEADO, NOMBRE FROM [EXACTUS].[INKA].[EMPLEADO]
    UNION ALL SELECT 'MUNDIAL', EMPLEADO, NOMBRE FROM [EXACTUS].[MUNDIAL].[EMPLEADO]
    UNION ALL SELECT 'NK', EMPLEADO, NOMBRE FROM [EXACTUS].[NK].[EMPLEADO]
    UNION ALL SELECT 'POLYSOL', EMPLEADO, NOMBRE FROM [EXACTUS].[POLYSOL].[EMPLEADO]
    UNION ALL SELECT 'SERVIAM', EMPLEADO, NOMBRE FROM [EXACTUS].[SERVIAM].[EMPLEADO]
    UNION ALL SELECT 'TROPICAL', EMPLEADO, NOMBRE FROM [EXACTUS].[TROPICAL].[EMPLEADO]
)
SELECT EMPRESA, EMPLEADO, COUNT(*) AS OCURRENCIAS
FROM EMPLEADOS
WHERE NULLIF(LTRIM(RTRIM(EMPLEADO)), '') IS NOT NULL
GROUP BY EMPRESA, EMPLEADO
HAVING COUNT(*) > 1
ORDER BY EMPRESA, EMPLEADO;
GO

/* 05.2 — Mismo código en más de una empresa. NO implica la misma persona. */
WITH EMPLEADOS AS (
    SELECT 'ANDINA' AS EMPRESA, EMPLEADO, NOMBRE FROM [EXACTUS].[ANDINA].[EMPLEADO]
    UNION ALL SELECT 'CALCA', EMPLEADO, NOMBRE FROM [EXACTUS].[CALCA].[EMPLEADO]
    UNION ALL SELECT 'FILASUR', EMPLEADO, NOMBRE FROM [EXACTUS].[FILASUR].[EMPLEADO]
    UNION ALL SELECT 'INKA', EMPLEADO, NOMBRE FROM [EXACTUS].[INKA].[EMPLEADO]
    UNION ALL SELECT 'MUNDIAL', EMPLEADO, NOMBRE FROM [EXACTUS].[MUNDIAL].[EMPLEADO]
    UNION ALL SELECT 'NK', EMPLEADO, NOMBRE FROM [EXACTUS].[NK].[EMPLEADO]
    UNION ALL SELECT 'POLYSOL', EMPLEADO, NOMBRE FROM [EXACTUS].[POLYSOL].[EMPLEADO]
    UNION ALL SELECT 'SERVIAM', EMPLEADO, NOMBRE FROM [EXACTUS].[SERVIAM].[EMPLEADO]
    UNION ALL SELECT 'TROPICAL', EMPLEADO, NOMBRE FROM [EXACTUS].[TROPICAL].[EMPLEADO]
)
SELECT
    EMPLEADO,
    COUNT(DISTINCT EMPRESA) AS EMPRESAS
FROM EMPLEADOS
WHERE NULLIF(LTRIM(RTRIM(EMPLEADO)), '') IS NOT NULL
GROUP BY EMPLEADO
HAVING COUNT(DISTINCT EMPRESA) > 1
ORDER BY EMPLEADO;

/* Para ver las empresas de un código concreto, use 05.5 cambiando la
   comparación por EMPLEADO = @codigo. */
GO

/* 05.3 — Mismo nombre normalizado en varias empresas. Es solo una señal para
   revisión manual; no se debe fusionar automáticamente. */
WITH EMPLEADOS AS (
    SELECT 'ANDINA' AS EMPRESA, EMPLEADO, NOMBRE,
           UPPER(LTRIM(RTRIM(NOMBRE))) AS NOMBRE_CLAVE
    FROM [EXACTUS].[ANDINA].[EMPLEADO]
    UNION ALL SELECT 'CALCA', EMPLEADO, NOMBRE, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[CALCA].[EMPLEADO]
    UNION ALL SELECT 'FILASUR', EMPLEADO, NOMBRE, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[FILASUR].[EMPLEADO]
    UNION ALL SELECT 'INKA', EMPLEADO, NOMBRE, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[INKA].[EMPLEADO]
    UNION ALL SELECT 'MUNDIAL', EMPLEADO, NOMBRE, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[MUNDIAL].[EMPLEADO]
    UNION ALL SELECT 'NK', EMPLEADO, NOMBRE, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[NK].[EMPLEADO]
    UNION ALL SELECT 'POLYSOL', EMPLEADO, NOMBRE, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[POLYSOL].[EMPLEADO]
    UNION ALL SELECT 'SERVIAM', EMPLEADO, NOMBRE, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[SERVIAM].[EMPLEADO]
    UNION ALL SELECT 'TROPICAL', EMPLEADO, NOMBRE, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[TROPICAL].[EMPLEADO]
)
SELECT
    NOMBRE_CLAVE,
    COUNT(*) AS REGISTROS,
    COUNT(DISTINCT EMPRESA) AS EMPRESAS
FROM EMPLEADOS
WHERE NULLIF(NOMBRE_CLAVE, '') IS NOT NULL
GROUP BY NOMBRE_CLAVE
HAVING COUNT(*) > 1
ORDER BY REGISTROS DESC, NOMBRE_CLAVE;

/* El detalle se obtiene con 05.5 indicando el nombre en @nombre. */
GO

/* 05.4 — Mismo nombre con ACTIVO distinto entre empresas (S/N o 1/0).
   Se muestran todos los registros para que el usuario elija, nunca se prioriza
   el orden de las empresas. */
WITH EMPLEADOS AS (
    SELECT 'ANDINA' AS EMPRESA, EMPLEADO, NOMBRE, ACTIVO,
           UPPER(LTRIM(RTRIM(NOMBRE))) AS NOMBRE_CLAVE
    FROM [EXACTUS].[ANDINA].[EMPLEADO]
    UNION ALL SELECT 'CALCA', EMPLEADO, NOMBRE, ACTIVO, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[CALCA].[EMPLEADO]
    UNION ALL SELECT 'FILASUR', EMPLEADO, NOMBRE, ACTIVO, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[FILASUR].[EMPLEADO]
    UNION ALL SELECT 'INKA', EMPLEADO, NOMBRE, ACTIVO, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[INKA].[EMPLEADO]
    UNION ALL SELECT 'MUNDIAL', EMPLEADO, NOMBRE, ACTIVO, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[MUNDIAL].[EMPLEADO]
    UNION ALL SELECT 'NK', EMPLEADO, NOMBRE, ACTIVO, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[NK].[EMPLEADO]
    UNION ALL SELECT 'POLYSOL', EMPLEADO, NOMBRE, ACTIVO, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[POLYSOL].[EMPLEADO]
    UNION ALL SELECT 'SERVIAM', EMPLEADO, NOMBRE, ACTIVO, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[SERVIAM].[EMPLEADO]
    UNION ALL SELECT 'TROPICAL', EMPLEADO, NOMBRE, ACTIVO, UPPER(LTRIM(RTRIM(NOMBRE))) FROM [EXACTUS].[TROPICAL].[EMPLEADO]
)
SELECT NOMBRE_CLAVE, COUNT(DISTINCT ACTIVO) AS ESTADOS_DISTINTOS,
       COUNT(DISTINCT EMPRESA) AS EMPRESAS
FROM EMPLEADOS
WHERE NULLIF(NOMBRE_CLAVE, '') IS NOT NULL
GROUP BY NOMBRE_CLAVE
HAVING COUNT(DISTINCT ACTIVO) > 1
ORDER BY NOMBRE_CLAVE;
GO

/* 05.5 — Detalle de los registros involucrados en 05.4, para selección manual.
   Reemplace @nombre por el nombre exacto que desea revisar. */
DECLARE @nombre AS nvarchar(200) = N'';
IF @nombre <> N''
BEGIN
    WITH EMPLEADOS AS (
        SELECT 'ANDINA' AS EMPRESA, EMPLEADO, NOMBRE, ACTIVO, 'EMPLEADO' AS FUENTE
        FROM [EXACTUS].[ANDINA].[EMPLEADO]
        UNION ALL SELECT 'CALCA', EMPLEADO, NOMBRE, ACTIVO, 'EMPLEADO' FROM [EXACTUS].[CALCA].[EMPLEADO]
        UNION ALL SELECT 'FILASUR', EMPLEADO, NOMBRE, ACTIVO, 'EMPLEADO' FROM [EXACTUS].[FILASUR].[EMPLEADO]
        UNION ALL SELECT 'INKA', EMPLEADO, NOMBRE, ACTIVO, 'EMPLEADO' FROM [EXACTUS].[INKA].[EMPLEADO]
        UNION ALL SELECT 'MUNDIAL', EMPLEADO, NOMBRE, ACTIVO, 'EMPLEADO' FROM [EXACTUS].[MUNDIAL].[EMPLEADO]
        UNION ALL SELECT 'NK', EMPLEADO, NOMBRE, ACTIVO, 'EMPLEADO' FROM [EXACTUS].[NK].[EMPLEADO]
        UNION ALL SELECT 'POLYSOL', EMPLEADO, NOMBRE, ACTIVO, 'EMPLEADO' FROM [EXACTUS].[POLYSOL].[EMPLEADO]
        UNION ALL SELECT 'SERVIAM', EMPLEADO, NOMBRE, ACTIVO, 'EMPLEADO' FROM [EXACTUS].[SERVIAM].[EMPLEADO]
        UNION ALL SELECT 'TROPICAL', EMPLEADO, NOMBRE, ACTIVO, 'EMPLEADO' FROM [EXACTUS].[TROPICAL].[EMPLEADO]
    )
    SELECT EMPRESA, FUENTE, EMPLEADO, NOMBRE, ACTIVO
    FROM EMPLEADOS
    WHERE UPPER(LTRIM(RTRIM(NOMBRE))) = UPPER(LTRIM(RTRIM(@nombre)))
    ORDER BY EMPRESA, EMPLEADO;
END
ELSE
BEGIN
    SELECT CAST('PENDIENTE DE VALIDACIÓN EN SSMS: asigne @nombre para ver el detalle.' AS varchar(200)) AS RESULTADO;
END
GO
