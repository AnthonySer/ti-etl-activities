/* ============================================================================
   01_validar_columnas.sql
   Objetivo: comprobar, empresa por empresa, qué columnas de EMPLEADO existen.

   Clasificación usada por el código:
     FUNDAMENTALES:
       - EMPLEADO (código)
       - NOMBRE, o en su defecto NOMBRE_PILA + PRIMER_APELLIDO + SEGUNDO_APELLIDO
     COMPLEMENTARIAS (opcionales):
       - DEPARTAMENTO, PUESTO, ACTIVO, ESTADO_EMPLEADO, E_MAIL,
         U_CORREO_CORP
     NO EXISTENTE EN NINGUNA EMPRESA (según diagnóstico 2026-11-11):
       - FUENTE (se genera como literal 'EMPLEADO' en el SELECT)

   SOLO LECTURA. No modifica estructuras ni datos.
   ============================================================================ */

USE [EXACTUS];
GO

/* 01.1 — Matriz 1/0 de columnas candidatas por empresa.
   Si una columna vale 0, el SELECT adaptativo debe omitirla. */
SELECT
    c.TABLE_SCHEMA AS EMPRESA,
    MAX(CASE WHEN c.COLUMN_NAME = 'EMPLEADO'          THEN 1 ELSE 0 END) AS TIENE_EMPLEADO,
    MAX(CASE WHEN c.COLUMN_NAME = 'NOMBRE'            THEN 1 ELSE 0 END) AS TIENE_NOMBRE,
    MAX(CASE WHEN c.COLUMN_NAME = 'NOMBRE_PILA'       THEN 1 ELSE 0 END) AS TIENE_NOMBRE_PILA,
    MAX(CASE WHEN c.COLUMN_NAME = 'PRIMER_APELLIDO'   THEN 1 ELSE 0 END) AS TIENE_PRIMER_APELLIDO,
    MAX(CASE WHEN c.COLUMN_NAME = 'SEGUNDO_APELLIDO'  THEN 1 ELSE 0 END) AS TIENE_SEGUNDO_APELLIDO,
    MAX(CASE WHEN c.COLUMN_NAME = 'DEPARTAMENTO'      THEN 1 ELSE 0 END) AS TIENE_DEPARTAMENTO,
    MAX(CASE WHEN c.COLUMN_NAME = 'PUESTO'            THEN 1 ELSE 0 END) AS TIENE_PUESTO,
    MAX(CASE WHEN c.COLUMN_NAME = 'ACTIVO'            THEN 1 ELSE 0 END) AS TIENE_ACTIVO,
    MAX(CASE WHEN c.COLUMN_NAME = 'ESTADO_EMPLEADO'   THEN 1 ELSE 0 END) AS TIENE_ESTADO_EMPLEADO,
    MAX(CASE WHEN c.COLUMN_NAME = 'E_MAIL'            THEN 1 ELSE 0 END) AS TIENE_E_MAIL,
    MAX(CASE WHEN c.COLUMN_NAME = 'U_CORREO_CORP'     THEN 1 ELSE 0 END) AS TIENE_U_CORREO_CORP,
    MAX(CASE WHEN c.COLUMN_NAME = 'FUENTE'            THEN 1 ELSE 0 END) AS TIENE_FUENTE
FROM INFORMATION_SCHEMA.COLUMNS AS c
WHERE c.TABLE_NAME = 'EMPLEADO'
  AND c.TABLE_SCHEMA IN (
    'ANDINA', 'CALCA', 'CONDOR', 'COYA', 'ESTRATEGO', 'FILASUR',
    'INKA', 'MUNDIAL', 'NK', 'POLYSOL', 'PROEXPLOR', 'RELTEX',
    'SERVIAM', 'TANKARPATA', 'TARAY', 'TMI', 'TROPICAL', 'YACLOT'
  )
GROUP BY c.TABLE_SCHEMA
ORDER BY c.TABLE_SCHEMA;
GO

/* 01.2 — Detalle de columnas que faltan respecto a la lista candidata.
   Sirve para explicar por qué una empresa no puede usar la consulta completa. */
WITH EMPRESAS AS (
    SELECT name AS EMPRESA
    FROM sys.schemas
    WHERE name IN (
        'ANDINA', 'CALCA', 'CONDOR', 'COYA', 'ESTRATEGO', 'FILASUR',
        'INKA', 'MUNDIAL', 'NK', 'POLYSOL', 'PROEXPLOR', 'RELTEX',
        'SERVIAM', 'TANKARPATA', 'TARAY', 'TMI', 'TROPICAL', 'YACLOT'
    )
),
CANDIDATAS AS (
    SELECT * FROM (VALUES
        ('EMPLEADO',         'FUNDAMENTAL'),
        ('NOMBRE',           'FUNDAMENTAL'),
        ('NOMBRE_PILA',      'FUNDAMENTAL ALTERNATIVA'),
        ('PRIMER_APELLIDO',  'FUNDAMENTAL ALTERNATIVA'),
        ('SEGUNDO_APELLIDO', 'FUNDAMENTAL ALTERNATIVA'),
        ('DEPARTAMENTO',     'COMPLEMENTARIA'),
        ('PUESTO',           'COMPLEMENTARIA'),
        ('ACTIVO',           'COMPLEMENTARIA'),
        ('ESTADO_EMPLEADO',  'COMPLEMENTARIA'),
        ('E_MAIL',           'COMPLEMENTARIA'),
        ('U_CORREO_CORP',    'COMPLEMENTARIA'),
        ('FUENTE',           'NO EXISTE EN NINGUNA EMPRESA')
    ) AS v(COLUMNA, CLASIFICACION)
)
SELECT
    e.EMPRESA,
    c.COLUMNA,
    c.CLASIFICACION,
    CASE WHEN col.COLUMN_NAME IS NULL THEN 'FALTA' ELSE 'EXISTE' END AS ESTADO
FROM EMPRESAS AS e
CROSS JOIN CANDIDATAS AS c
LEFT JOIN INFORMATION_SCHEMA.COLUMNS AS col
    ON col.TABLE_SCHEMA = e.EMPRESA
   AND col.TABLE_NAME = 'EMPLEADO'
   AND col.COLUMN_NAME = c.COLUMNA
WHERE col.COLUMN_NAME IS NULL
ORDER BY e.EMPRESA, c.CLASIFICACION, c.COLUMNA;
GO

/* 01.3 — ¿Existen las tablas de catálogo y sus columnas de unión?
   El código solo hace LEFT JOIN si existen DEPARTAMENTO.DESCRIPCION y
   PUESTO.DESCRIPCION, además de la columna de código en EMPLEADO. */
SELECT
    t.TABLE_SCHEMA AS EMPRESA,
    t.TABLE_NAME AS TABLA,
    MAX(CASE WHEN c.COLUMN_NAME = 'DESCRIPCION' THEN 1 ELSE 0 END) AS TIENE_DESCRIPCION,
    MAX(CASE WHEN c.COLUMN_NAME = 'DEPARTAMENTO' THEN 1 ELSE 0 END) AS TIENE_CODIGO_DEPARTAMENTO,
    MAX(CASE WHEN c.COLUMN_NAME = 'PUESTO' THEN 1 ELSE 0 END) AS TIENE_CODIGO_PUESTO
FROM INFORMATION_SCHEMA.TABLES AS t
LEFT JOIN INFORMATION_SCHEMA.COLUMNS AS c
    ON c.TABLE_SCHEMA = t.TABLE_SCHEMA
   AND c.TABLE_NAME = t.TABLE_NAME
WHERE t.TABLE_SCHEMA IN (
    'ANDINA', 'CALCA', 'CONDOR', 'COYA', 'ESTRATEGO', 'FILASUR',
    'INKA', 'MUNDIAL', 'NK', 'POLYSOL', 'PROEXPLOR', 'RELTEX',
    'SERVIAM', 'TANKARPATA', 'TARAY', 'TMI', 'TROPICAL', 'YACLOT'
)
  AND t.TABLE_NAME IN ('DEPARTAMENTO', 'PUESTO')
GROUP BY t.TABLE_SCHEMA, t.TABLE_NAME
ORDER BY t.TABLE_SCHEMA, t.TABLE_NAME;
GO
